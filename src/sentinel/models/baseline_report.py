"""Render docs/BASELINE.md: LightGBM vs logistic regression at a FIXED FPR, with intervals."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

NAMES = {"lightgbm": "LightGBM (v1)", "logreg": "Logistic regression"}


def _pct(x: float, digits: int = 2) -> str:
    return f"{100 * x:.{digits}f}%"


def _ci(ci: list[float], digits: int = 2) -> str:
    return f"[{_pct(ci[0], digits)}, {_pct(ci[1], digits)}]"


def _span(weeks: list[int]) -> str:
    return f"{weeks[0]}-{weeks[-1]}" if len(weeks) > 1 else str(weeks[0])


def _overlap(a: list[float], b: list[float]) -> bool:
    return a[0] <= b[1] and b[0] <= a[1]


def read_metrics(models_dir: Path) -> dict[str, tuple[dict[str, Any], dict[str, Any]]]:
    """{file_type: (metrics, run_info)} from docs/models/<type>/{metrics,run_info}.json."""
    out = {}
    for d in sorted(p for p in models_dir.iterdir() if p.is_dir()):
        m, r = d / "metrics.json", d / "run_info.json"
        if m.is_file() and r.is_file():
            out[d.name] = (
                json.loads(m.read_text(encoding="utf-8")),
                json.loads(r.read_text(encoding="utf-8")),
            )
    return out


def render_baseline(results: dict[str, tuple[dict[str, Any], dict[str, Any]]]) -> str:
    out = [
        "# Baseline — LightGBM vs logistic regression",
        "",
        "_Generated by `scripts/register_model.py` from each dataset's `metrics.json`. All numbers "
        "are measured. Every comparison is at a FIXED false-positive rate chosen on the "
        "calibration weeks (never on test weeks), not at threshold 0.5. Intervals are 95% Wilson._",
        "",
    ]
    if not results:
        return "\n".join([*out, "No trained models yet.", ""])
    for ft, (m, info) in results.items():
        w, c = info["windows"], info["counts"]
        fpr = m["target_fpr"]
        lg, lr = m["models"]["lightgbm"], m["models"]["logreg"]
        out += [
            f"## {ft}",
            "",
            f"- Fit weeks {_span(w['fit'])} ({c['fit']['rows']:,} files with a label known by "
            f"{w['as_of']}; {c['fit']['unlabelled_dropped']:,} left out as not yet labelled); "
            f"calibration + threshold weeks {_span(w['calibration'])} "
            f"({c['calibration']['rows']:,} files, {c['calibration']['benign']:,} benign; "
            f"{c['calibration']['unlabelled_dropped']:,} not yet labelled); "
            f"validation week {w['eval_week']} ({c['eval']['rows']:,} files).",
            f"- Target FPR **{_pct(fpr, 2)}**; seed `{info['seed']}`; "
            f"feature_schema_version `{info['feature_schema_version']}`; "
            f"data fingerprint `{info['data_fingerprint'][:16]}...`; "
            f"commit `{info['git_commit']}`.",
            f"- Logistic regression is fit on a seeded subsample of {c['logreg_rows']:,} "
            "fit-week files.",
            "",
            f"### Validation week {w['eval_week']} (K+1)",
            "",
            "| Model | Recall at fixed FPR | 95% CI | Measured FPR | 95% CI | AUC | AUPRC "
            "| ECE (calibrated) |",
            "|---|---:|---|---:|---|---:|---:|---:|",
        ]
        for key in ("lightgbm", "logreg"):
            e = m["models"][key]["eval_week"]
            out.append(
                f"| {NAMES[key]} | {_pct(e['recall'])} | {_ci(e['recall_ci'])} | "
                f"{_pct(e['fpr'], 3)} | {_ci(e['fpr_ci'], 3)} | {e['auc']:.4f} | "
                f"{e['auprc']:.4f} | {e['ece']:.4f} |"
            )
        ev_lg, ev_lr = lg["eval_week"], lr["eval_week"]
        gap = ev_lg["recall"] - ev_lr["recall"]
        overlap = _overlap(ev_lg["recall_ci"], ev_lr["recall_ci"])
        out += [
            "",
            f"Recall difference (LightGBM minus LR): **{100 * gap:+.2f} points**; the recall "
            f"intervals {'overlap' if overlap else 'do not overlap'}.",
        ]
        if "test_weeks_report_only" in lg:
            out += [
                "",
                f"### Test weeks {_span(w['test_report_only'])} (report only: same fixed "
                "threshold, nothing tuned here)",
                "",
                "| Model | Recall | 95% CI | FPR | 95% CI | AUC | Benign files |",
                "|---|---:|---|---:|---|---:|---:|",
            ]
            for key in ("lightgbm", "logreg"):
                p = m["models"][key]["test_weeks_report_only"]["pooled"]
                out.append(
                    f"| {NAMES[key]} | {_pct(p['recall'])} | {_ci(p['recall_ci'])} | "
                    f"{_pct(p['fpr'], 3)} | {_ci(p['fpr_ci'], 3)} | {p['auc']:.4f} | "
                    f"{p['negatives']:,} |"
                )
            out += [
                "",
                "<details><summary>Per test week (LightGBM v1)</summary>",
                "",
                "| Week | Recall | FPR | False alarms / benign |",
                "|---:|---:|---:|---:|",
            ]
            for r in lg["test_weeks_report_only"]["per_week"]:
                out.append(
                    f"| {r['week']} | {_pct(r['recall'])} | {_pct(r['fpr'], 3)} | "
                    f"{r['fp']:,} / {r['negatives']:,} |"
                )
            out += ["", "</details>"]
        out += [
            "",
            "### Threshold, never-break set",
            "",
            "| Model | Raw threshold | Calibrated probability at threshold "
            "| FPR on calibration weeks | Never-break flags |",
            "|---|---:|---:|---:|---:|",
        ]
        for key in ("lightgbm", "logreg"):
            mm = m["models"][key]
            out.append(
                f"| {NAMES[key]} | {mm['threshold_raw']:.6f} | {mm['threshold_probability']:.4f} | "
                f"{_pct(mm['calibration']['fpr'], 3)} | {mm['never_break_flags']} / "
                f"{mm['never_break_rows']} |"
            )
        out.append("")
    return "\n".join(out) + "\n"


def build_baseline(models_dir: Path, out: Path) -> list[str]:
    results = read_metrics(models_dir) if models_dir.is_dir() else {}
    out.write_text(render_baseline(results), encoding="utf-8")
    return list(results)
